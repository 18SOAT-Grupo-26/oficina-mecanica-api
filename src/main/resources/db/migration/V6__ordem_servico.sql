-- Ordem de Serviço: a OS, seus itens (serviços e peças com preço congelado) e o histórico de status.
-- Cliente, veículo, serviço e peça são referências aos cadastros existentes.

create table ordem_servico
(
    id         bigint generated by default as identity primary key,
    -- cliente e veículo são definidos na abertura e não mudam depois
    cliente_id bigint                      not null
        constraint fk_ordem_servico_cliente references clientes,
    veiculo_id bigint                      not null
        constraint fk_ordem_servico_veiculo references veiculos,
    status     varchar(30)                 not null
        constraint ck_ordem_servico_status check (status in
                                                  ('RECEBIDA', 'EM_DIAGNOSTICO', 'AGUARDANDO_APROVACAO', 'EM_EXECUCAO',
                                                   'FINALIZADA', 'ENTREGUE', 'CANCELADA')),
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null
);

create index idx_ordem_servico_cliente on ordem_servico (cliente_id);
create index idx_ordem_servico_status on ordem_servico (status);

-- sem unique (OS, serviço): mudar a quantidade troca o item, e o Hibernate insere antes de apagar
create table item_servico_os
(
    id               bigint generated by default as identity primary key,
    ordem_servico_id bigint         not null
        constraint fk_item_servico_os_ordem references ordem_servico,
    servico_id       bigint         not null
        constraint fk_item_servico_os_servico references servico,
    descricao        varchar(255)   not null,
    preco_unitario   numeric(12, 2) not null
        constraint ck_item_servico_os_preco check (preco_unitario >= 0),
    quantidade       integer        not null
        constraint ck_item_servico_os_quantidade check (quantidade > 0)
);

create index idx_item_servico_os_ordem on item_servico_os (ordem_servico_id);

create table item_peca_os
(
    id               bigint generated by default as identity primary key,
    ordem_servico_id bigint         not null
        constraint fk_item_peca_os_ordem references ordem_servico,
    peca_insumo_id   bigint         not null
        constraint fk_item_peca_os_peca references peca_insumo,
    descricao        varchar(255)   not null,
    preco_unitario   numeric(12, 2) not null
        constraint ck_item_peca_os_preco check (preco_unitario >= 0),
    quantidade       integer        not null
        constraint ck_item_peca_os_quantidade check (quantidade > 0)
);

create index idx_item_peca_os_ordem on item_peca_os (ordem_servico_id);

-- colunas combinadas com a Ana; status_antigo fica vazio só no registro da abertura (RECEBIDA)
create table historico_status_os
(
    id_historico      bigint generated by default as identity primary key,
    id_os             bigint                      not null
        constraint fk_historico_status_os_ordem references ordem_servico,
    status_antigo     varchar(30)
        constraint ck_historico_status_os_antigo check (status_antigo in
                                                        ('RECEBIDA', 'EM_DIAGNOSTICO', 'AGUARDANDO_APROVACAO',
                                                         'EM_EXECUCAO',
                                                         'FINALIZADA', 'ENTREGUE', 'CANCELADA')),
    status_atualizado varchar(30)                 not null
        constraint ck_historico_status_os_atualizado check (status_atualizado in
                                                            ('RECEBIDA', 'EM_DIAGNOSTICO', 'AGUARDANDO_APROVACAO',
                                                             'EM_EXECUCAO',
                                                             'FINALIZADA', 'ENTREGUE', 'CANCELADA')),
    data_criacao      timestamp(6) with time zone not null
);

-- serve à listagem do histórico da OS e ao cálculo do tempo médio (EM_EXECUCAO → FINALIZADA)
create index idx_historico_status_os_ordem_status on historico_status_os (id_os, status_atualizado);
