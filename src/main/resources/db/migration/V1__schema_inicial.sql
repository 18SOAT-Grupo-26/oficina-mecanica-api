-- Schema inicial, espelhando as entidades JPA existentes.
-- O Hibernate roda com ddl-auto=validate: toda mudança de entidade exige uma nova migration (V2__, V3__...).
-- Nunca edite uma migration já aplicada.

-- Autenticação e autorização --------------------------------------------------------------------

create table permissions
(
    id          bigint generated by default as identity primary key,
    name        varchar(255) not null
        constraint uk_permissions_name unique,
    description varchar(255),
    created_at  timestamp(6) with time zone,
    updated_at  timestamp(6) with time zone
);

create table roles
(
    id          bigint generated by default as identity primary key,
    name        varchar(255) not null
        constraint uk_roles_name unique,
    description varchar(255),
    created_at  timestamp(6) with time zone,
    updated_at  timestamp(6) with time zone
);

create table role_permissions
(
    role_id       bigint not null
        constraint fk_role_permissions_role references roles,
    permission_id bigint not null
        constraint fk_role_permissions_permission references permissions,
    primary key (permission_id, role_id)
);

-- Identidade dos usuários do sistema ------------------------------------------------------------

create table contacts
(
    id           bigint generated by default as identity primary key,
    phone_number varchar(255),
    email        varchar(255),
    created_at   timestamp(6) with time zone,
    updated_at   timestamp(6) with time zone
);

create table addresses
(
    id         bigint generated by default as identity primary key,
    street     varchar(255),
    number     varchar(255),
    district   varchar(255),
    city       varchar(255),
    state      varchar(255),
    zip_code   varchar(255),
    complement varchar(255),
    created_at timestamp(6) with time zone,
    updated_at timestamp(6) with time zone
);

create table identities
(
    id            bigint generated by default as identity primary key,
    full_name     varchar(255),
    given_name    varchar(255),
    cpf           varchar(255),
    rg            varchar(255),
    date_of_birth date,
    contact_id    bigint
        constraint uk_identities_contact unique
        constraint fk_identities_contact references contacts,
    address_id    bigint
        constraint uk_identities_address unique
        constraint fk_identities_address references addresses,
    active        boolean not null,
    created_at    timestamp(6) with time zone,
    updated_at    timestamp(6) with time zone
);

create table users
(
    id              bigint generated by default as identity primary key,
    identity_id     bigint
        constraint uk_users_identity unique
        constraint fk_users_identity references identities,
    username        varchar(255),
    password        varchar(255),
    change_required boolean default false not null,
    role_id         bigint                not null
        constraint fk_users_role references roles,
    active          boolean               not null,
    created_at      timestamp(6) with time zone,
    updated_at      timestamp(6) with time zone
);

-- Catálogo: peças, insumos e serviços -----------------------------------------------------------

create table peca_insumo
(
    id               bigint generated by default as identity primary key,
    nome             varchar(255)                not null,
    nome_normalizado varchar(255)                not null
        constraint uk_peca_insumo_nome_normalizado unique,
    descricao        varchar(255),
    quantidade       integer                     not null,
    reservado        integer                     not null,
    preco            numeric(12, 2)              not null,
    created_at       timestamp(6) with time zone not null,
    updated_at       timestamp(6) with time zone not null
);

create table servico
(
    id               bigint generated by default as identity primary key,
    nome             varchar(255)                not null,
    nome_normalizado varchar(255)                not null
        constraint uk_servico_nome_normalizado unique,
    descricao        varchar(255),
    preco            numeric(12, 2)              not null,
    created_at       timestamp(6) with time zone not null,
    updated_at       timestamp(6) with time zone not null
);

-- sem chave primária: a entidade mapeia List, que admite a mesma peça mais de uma vez
create table servico_peca_insumo
(
    servico_id     bigint not null
        constraint fk_servico_peca_insumo_servico references servico,
    peca_insumo_id bigint not null
        constraint fk_servico_peca_insumo_peca references peca_insumo
);

create index idx_servico_peca_insumo_servico on servico_peca_insumo (servico_id);

-- Clientes e veículos ---------------------------------------------------------------------------

create table clientes
(
    id             bigint generated by default as identity primary key,
    nome           varchar(255)                not null,
    documento      varchar(14)                 not null
        constraint uk_clientes_documento unique,
    tipo_documento varchar(4)                  not null
        constraint ck_clientes_tipo_documento check (tipo_documento in ('CPF', 'CNPJ')),
    email          varchar(255)                not null,
    telefone       varchar(255)                not null,
    logradouro     varchar(255),
    numero         varchar(255),
    bairro         varchar(255),
    cidade         varchar(255),
    estado         varchar(255),
    cep            varchar(255),
    complemento    varchar(255),
    ativo          boolean                     not null,
    created_at     timestamp(6) with time zone not null,
    updated_at     timestamp(6) with time zone not null
);

create table veiculos
(
    id         bigint generated by default as identity primary key,
    placa      varchar(7)                  not null
        constraint uk_veiculos_placa unique,
    marca      varchar(255)                not null,
    modelo     varchar(255)                not null,
    ano        integer                     not null,
    cliente_id bigint                      not null
        constraint fk_veiculos_cliente references clientes,
    ativo      boolean                     not null,
    created_at timestamp(6) with time zone not null,
    updated_at timestamp(6) with time zone not null
);

create index idx_veiculos_cliente on veiculos (cliente_id);
